// @ts-check
import { defineConfig } from 'astro/config';
import tailwindcss from '@tailwindcss/vite';
import sitemap from '@astrojs/sitemap';

// https://astro.build/config
export default defineConfig({
  site: 'https://suhbalibrary.org',
  output: 'static',

  integrations: [
    sitemap({
      // Exclude JSON data endpoints and feeds from the sitemap — they're not web pages
      filter: (page) =>
        !page.includes('/indexes/') &&
        !page.endsWith('/search-index.json') &&
        !page.endsWith('/rss.xml'),
    }),
  ],

  vite: {
    plugins: [
      // Tailwind v4 integrates via Vite plugin, not Astro integration
      tailwindcss(),
    ],
    build: {
      rollupOptions: {
        // /pagefind/ files are generated by the pagefind postbuild hook and
        // do not exist at bundle time — tell Rollup to leave these imports alone.
        external: [/^\/pagefind\//],
      },
    },
  },

  // Content Collections require explicit glob loaders — see src/content/config.ts

  // Build options
  build: {
    // Inline small assets to reduce requests
    inlineStylesheets: 'auto',
  },

  // Image optimisation — no external service; static only
  image: {
    // R2 images are referenced by absolute URL; no local optimisation needed
    remotePatterns: [
      {
        protocol: 'https',
        hostname: '**.r2.suhbalibrary.org',
      },
      {
        protocol: 'https',
        hostname: 'r2.suhbalibrary.org',
      },
    ],
  },
});
